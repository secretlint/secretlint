#!/usr/bin/env node
// Build wasm/keyword-scan.c and write the result to src/helper/keyword-scan-wasm.ts as a base64 string.
// The WebAssembly module is a string in a JavaScript module, so it is distributed like other code:
// npm, a bundler for browsers, and the single-executable binary need nothing else.
//
// Requirements: clang and wasm-ld (LLVM) that support the wasm32 target.
// Usage: node scripts/build-wasm.mjs [--check]
//   --check: do not write. Exit with 1 if the file is different from the build result.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const packageDir = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = path.join(packageDir, "wasm/keyword-scan.c");
const output = path.join(packageDir, "src/helper/keyword-scan-wasm.ts");
const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), "secretlint-wasm-"));
const wasmFile = path.join(tmpDir, "keyword-scan.wasm");
try {
    execFileSync(
        "clang",
        [
            "--target=wasm32",
            "-O3",
            "-msimd128",
            "-nostdlib",
            "-Wl,--no-entry",
            "-Wl,--strip-all",
            // The input is written after the data of the module, and the memory grows for a large input
            "-Wl,--export=__heap_base",
            "-o",
            wasmFile,
            source,
        ],
        { stdio: "inherit" },
    );
    const wasm = fs.readFileSync(wasmFile);
    const base64 = wasm.toString("base64");
    const lines = base64.match(/.{1,100}/g) ?? [];
    const content = `// Generated by scripts/build-wasm.mjs from wasm/keyword-scan.c. Do not edit.
// ${wasm.length} bytes of WebAssembly as base64
export const KEYWORD_SCAN_WASM_BASE64 =
${lines.map((line) => `    "${line}"`).join(" +\n")};
`;
    if (process.argv.includes("--check")) {
        if (fs.readFileSync(output, "utf8") !== content) {
            console.error(`${path.relative(packageDir, output)} is not the build result of wasm/keyword-scan.c`);
            // Not process.exit(): the temporary directory is removed in `finally`
            process.exitCode = 1;
        } else {
            console.log("up to date");
        }
    } else {
        fs.writeFileSync(output, content);
        console.log(`wrote ${path.relative(packageDir, output)} (${wasm.length} bytes of WebAssembly)`);
    }
} finally {
    fs.rmSync(tmpDir, { recursive: true, force: true });
}
