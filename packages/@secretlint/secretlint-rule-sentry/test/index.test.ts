import assert from "node:assert/strict";
import test from "node:test";
import { lintSource } from "@secretlint/core";
import { snapshot } from "@secretlint/tester";
import { creator as rule, type Options } from "../src/index.js";

const personal = "sntryu_" + "0".repeat(64);
const app = "sntrya_" + "0".repeat(64);
const organization = "sntrys_eyJ0ZXN0IjoiZHVtbXkiLCJpYXQiOjB9_AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA";
const paddedOrganization = "sntrys_eyJpYXQiOjF9IA==_AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA";
const tokens = [
    ["SENTRY_ORGANIZATION_TOKEN", organization],
    ["SENTRY_PERSONAL_TOKEN", personal],
    ["SENTRY_USER_APP_TOKEN", app],
] as const;

const lint = (content: string, options: Options = {}, maskSecrets = false) =>
    lintSource({
        source: { content, filePath: "/test.txt", contentType: "text", ext: ".txt" },
        options: { config: { rules: [{ id: rule.meta.id, rule, options }] }, maskSecrets },
    });

for (const [messageId, token] of tokens) {
    test(`detects ${messageId} with an exact source range`, async () => {
        const { messages } = await lint(`token="${token}";`);
        assert.equal(messages.length, 1);
        assert.equal(messages[0].messageId, messageId);
        assert.deepEqual(messages[0].range, [7, 7 + token.length]);
    });

    test(`masks ${messageId} in diagnostic messages and data`, async () => {
        const { messages } = await lint(token, {}, true);
        assert.equal(messages.length, 1);
        assert.ok(!JSON.stringify(messages).includes(token));
        assert.match(messages[0].message, /\*+/);
    });

    test(`allows literal and regexp exclusions for ${messageId}`, async () => {
        assert.equal((await lint(token, { allows: [token] })).messages.length, 0);
        assert.equal((await lint(token, { allows: ["/^sntry[usa]_/i"] })).messages.length, 0);
        assert.equal((await lint(token, { allows: ["unrelated"] })).messages.length, 1);
    });

    test(`does not match ${messageId} inside a word or a longer token`, async () => {
        const { messages } = await lint(`prefix${token} \u65e5${token} ${token}a ${token}_suffix`);
        assert.equal(messages.length, 0);
    });
}

test("detects padded organization payloads generated by Sentry", async () => {
    const { messages } = await lint(paddedOrganization);
    assert.equal(messages.length, 1);
    assert.deepEqual(messages[0].range, [0, paddedOrganization.length]);
});

test("an allowlisted token does not suppress other tokens", async () => {
    const { messages } = await lint(`${personal}\n${app}`, { allows: [personal] });
    assert.deepEqual(
        messages.map(({ messageId }) => messageId),
        ["SENTRY_USER_APP_TOKEN"],
    );
});

test("detects tokens next to punctuation and Unicode whitespace", async () => {
    const { messages } = await lint(`(${personal}),\u3000${app};`);
    assert.equal(messages.length, 2);
});

test("supports URL-safe organization tokens and one padding character", async () => {
    const { messages } = await lint("sntrys_eyJpYXQiOjF9ICA=_" + "-_/+".repeat(10) + "AAA");
    assert.equal(messages.length, 1);
    assert.equal(messages[0].messageId, "SENTRY_ORGANIZATION_TOKEN");
});

test("reports every occurrence across lines", async () => {
    const { messages } = await lint(`${personal}\n${personal}\n${app}`);
    assert.deepEqual(
        messages.map(({ messageId }) => messageId),
        ["SENTRY_PERSONAL_TOKEN", "SENTRY_PERSONAL_TOKEN", "SENTRY_USER_APP_TOKEN"],
    );
});

test("ignores incomplete tokens, invalid alphabets, and public DSNs", async () => {
    const { messages } = await lint(
        [
            "sntrys_short",
            "sntryu_abcdef",
            "sntrya_",
            personal.slice(0, -1),
            app.slice(0, -1),
            "sntryu_" + "g".repeat(64),
            organization.slice(0, -1),
            "https://0123456789abcdef0123456789abcdef@o0.ingest.sentry.io/0",
        ].join("\n"),
    );
    assert.equal(messages.length, 0);
});

test("handles large near-matches without reporting partial tokens", { timeout: 5000 }, async () => {
    const { messages } = await lint(("sntrys_" + "A".repeat(400) + "_" + "A".repeat(101) + "\n").repeat(2000));
    assert.equal(messages.length, 0);
});

